begin;
set local lock_timeout='10s';
alter table public.equipment_assets
  add column archived_at timestamptz,
  add column archived_by uuid references public.profiles(id),
  add column archive_reason text;
create table public.equipment_incident_options (
  id bigint generated by default as identity primary key,
  equipment_id uuid not null references public.equipment_assets(id),
  label text not null check(length(btrim(label)) between 3 and 240),
  normalized_label text generated always as (lower(regexp_replace(btrim(label),'\s+',' ','g'))) stored,
  source text not null check(source in ('inventario','reporte')),
  created_at timestamptz not null default now(),
  unique(equipment_id,normalized_label)
);
alter table public.equipment_incident_options enable row level security;
create policy "staff read equipment incident taxonomy" on public.equipment_incident_options for select to authenticated using(public.is_technician_or_manager());
grant select on public.equipment_incident_options to authenticated;
revoke insert,update,delete on public.equipment_incident_options from authenticated,anon;

-- Import symptom labels, never narratives, patient outcomes or personal details.
insert into public.equipment_incident_options(equipment_id,label,source)
select distinct equipment_id,btrim(label),'inventario'
from public.equipment_inventory_extensions e cross join lateral regexp_split_to_table(e.possible_problems,E'[\n\r;,]+') label
where length(btrim(label)) between 3 and 240
on conflict(equipment_id,normalized_label) do nothing;
insert into public.equipment_incident_options(equipment_id,label,source)
select distinct equipment_id,btrim(event_type),'reporte' from public.reports
where equipment_id is not null and length(btrim(event_type)) between 3 and 240
on conflict(equipment_id,normalized_label) do nothing;

alter table public.reports add column incident_option_id bigint references public.equipment_incident_options(id),add column incident_label text;

create or replace function public.get_equipment_incident_options(target_equipment_id uuid)
returns jsonb language plpgsql stable security definer set search_path=public,pg_temp as $$
begin
  if not public.has_active_profile() then raise exception 'Perfil activo requerido'; end if;
  if not exists(select 1 from public.equipment_assets where id=target_equipment_id and active) then raise exception 'Equipo no disponible'; end if;
  return (select coalesce(jsonb_agg(jsonb_build_object('id',o.id,'label',o.label,'source',o.source,
    'report_count',(select count(*) from public.reports r where r.equipment_id=target_equipment_id
      and lower(regexp_replace(btrim(coalesce(r.incident_label,r.event_type)),'\s+',' ','g'))=o.normalized_label)) order by o.label),'[]'::jsonb)
    from public.equipment_incident_options o where o.equipment_id=target_equipment_id);
end $$;

create or replace function public.validate_report_incident_option()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare label_value text;
begin
  if tg_op='INSERT' and not exists(select 1 from public.equipment_assets where id=new.equipment_id and active) then raise exception 'El equipo fue retirado o no está disponible'; end if;
  if tg_op='UPDATE' and row(new.incident_option_id,new.incident_label) is distinct from row(old.incident_option_id,old.incident_label) then
    if not public.has_active_profile() or old.reporter_id<>auth.uid() or clock_timestamp()>=old.created_at+interval '10 minutes' then raise exception 'La corrección del incidente está cerrada'; end if;
  end if;
  if new.incident_option_id is not null then
    select label into label_value from public.equipment_incident_options where id=new.incident_option_id and equipment_id=new.equipment_id;
    if label_value is null then raise exception 'El incidente no pertenece al equipo seleccionado'; end if;
    new.incident_label:=label_value;
  else
    new.incident_label:=nullif(btrim(new.incident_label),'');
    if new.incident_label is not null and length(new.incident_label) not between 3 and 240 then raise exception 'Indica una falla breve, entre 3 y 240 caracteres'; end if;
  end if;
  return new;
end $$;
create trigger validate_report_incident_option before insert or update on public.reports for each row execute function public.validate_report_incident_option();
create or replace function public.remember_report_incident_option()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if new.equipment_id is not null and length(btrim(coalesce(new.incident_label,new.event_type))) between 3 and 240 then
    insert into public.equipment_incident_options(equipment_id,label,source) values(new.equipment_id,btrim(coalesce(new.incident_label,new.event_type)),'reporte') on conflict(equipment_id,normalized_label) do nothing;
  end if;
  return new;
end $$;
create trigger remember_report_incident_option after insert or update of incident_label,event_type on public.reports for each row execute function public.remember_report_incident_option();

create or replace function public.equipment_admin_context(target_equipment_id uuid default null)
returns jsonb language plpgsql stable security definer set search_path=public,pg_temp as $$
declare asset jsonb;
begin
  if not public.is_manager() then raise exception 'Solo el jefe puede administrar equipos'; end if;
  if target_equipment_id is not null then
    select to_jsonb(d)||jsonb_build_object('hospital_area_id',a.hospital_area_id,'location_id',a.location_id,'active',a.active,'serial_is_placeholder',a.serial_is_placeholder)
    into asset from public.equipment_inventory_detail d join public.equipment_assets a on a.id=d.id where d.id=target_equipment_id;
    if asset is null then raise exception 'Equipo no encontrado'; end if;
  end if;
  return jsonb_build_object('asset',asset,
    'areas',(select coalesce(jsonb_agg(jsonb_build_object('id',id,'name',name) order by name),'[]'::jsonb) from public.hospital_areas where active),
    'locations',(select coalesce(jsonb_agg(jsonb_build_object('id',id,'name',name,'hospital_area_id',hospital_area_id) order by name),'[]'::jsonb) from public.equipment_locations where active));
end $$;

create or replace function public.save_equipment_asset(target_equipment_id uuid,data jsonb,reason text)
returns uuid language plpgsql security definer set search_path=public,pg_temp as $$
declare type_id bigint;brand_id bigint;model_id bigint;asset_id uuid;code text;
  next_number integer;area_id bigint:=(data->>'hospital_area_id')::bigint;room_id bigint:=nullif(data->>'location_id','')::bigint;
begin
  if not public.is_manager() then raise exception 'Solo el jefe puede administrar equipos'; end if;
  if length(btrim(coalesce(reason,'')))<3 then raise exception 'Indica el motivo del cambio'; end if;
  if nullif(btrim(data->>'equipment_type'),'') is null or nullif(btrim(data->>'manufacturer'),'') is null or nullif(btrim(data->>'model'),'') is null then raise exception 'Nombre, fabricante y modelo son obligatorios'; end if;
  if not exists(select 1 from public.hospital_areas where id=area_id and active) then raise exception 'Área no disponible'; end if;
  if room_id is not null and not exists(select 1 from public.equipment_locations where id=room_id and hospital_area_id=area_id and active) then raise exception 'Ubicación incompatible con el área'; end if;
  perform pg_advisory_xact_lock(20261123,22);
  if target_equipment_id is not null then
    perform 1 from public.equipment_assets where id=target_equipment_id and active for update;
    if not found then raise exception 'Equipo no disponible; restaura un equipo retirado antes de editarlo'; end if;
  end if;
  select id into type_id from public.equipment_types where lower(btrim(name))=lower(btrim(data->>'equipment_type')) order by id limit 1;
  if type_id is null then insert into public.equipment_types(name) values(btrim(data->>'equipment_type')) returning id into type_id; end if;
  select id into brand_id from public.manufacturers where lower(btrim(name))=lower(btrim(data->>'manufacturer')) order by id limit 1;
  if brand_id is null then insert into public.manufacturers(name) values(btrim(data->>'manufacturer')) returning id into brand_id; end if;
  select id into model_id from public.equipment_models where equipment_type_id=type_id and manufacturer_id=brand_id and lower(btrim(name))=lower(btrim(data->>'model')) order by id limit 1;
  if model_id is null then insert into public.equipment_models(equipment_type_id,manufacturer_id,name) values(type_id,brand_id,btrim(data->>'model')) returning id into model_id; end if;
  if target_equipment_id is null then
    select coalesce(max(substring(inventory_code from 4)::integer),0)+1 into next_number from public.equipment_assets;
    if next_number>999999 then raise exception 'Se agotó la numeración de inventario'; end if;
    code:='EQ-'||lpad(next_number::text,6,'0');
    insert into public.equipment_assets(inventory_code,equipment_model_id,serial_number,serial_is_placeholder,manufacture_year,acquisition_year,hospital_area_id,location_id,custodian_location_text,status,requires_review)
    values(code,model_id,nullif(btrim(data->>'serial_number'),''),coalesce((data->>'serial_is_placeholder')::boolean,false),nullif(data->>'manufacture_year','')::smallint,nullif(data->>'acquisition_year','')::smallint,area_id,room_id,nullif(btrim(data->>'custodian_location_text'),''),coalesce(nullif(data->>'status',''),'desconocido')::public.equipment_status,true) returning id into asset_id;
  else
    update public.equipment_assets set equipment_model_id=model_id,serial_number=nullif(btrim(data->>'serial_number'),''),
      serial_is_placeholder=coalesce((data->>'serial_is_placeholder')::boolean,false),manufacture_year=nullif(data->>'manufacture_year','')::smallint,
      acquisition_year=nullif(data->>'acquisition_year','')::smallint,hospital_area_id=area_id,location_id=room_id,
      custodian_location_text=nullif(btrim(data->>'custodian_location_text'),''),status=coalesce(nullif(data->>'status',''),'desconocido')::public.equipment_status
    where id=target_equipment_id returning id into asset_id;
  end if;
  insert into public.audit_log(actor_id,action,entity_type,entity_id,metadata)
  values(auth.uid(),case when target_equipment_id is null then 'equipment_create' else 'equipment_edit' end,'equipment_assets',asset_id::text,jsonb_build_object('reason',btrim(reason)));
  return asset_id;
end $$;

create or replace function public.archive_equipment_asset(target_equipment_id uuid,reason text)
returns void language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if not public.is_manager() then raise exception 'Solo el jefe puede retirar equipos'; end if;
  if length(btrim(coalesce(reason,'')))<3 then raise exception 'Indica el motivo del retiro'; end if;
  perform pg_advisory_xact_lock(20261122,20);perform pg_advisory_xact_lock(20261123,22);
  perform 1 from public.equipment_assets where id=target_equipment_id and active for update;
  if not found then raise exception 'Equipo no disponible'; end if;
  if exists(select 1 from public.maintenances where equipment_id=target_equipment_id and status in ('programado','en_proceso'))
    or exists(select 1 from public.calendar_resource_events() e where e.blocks_resources and target_equipment_id=any(e.equipment_ids) and coalesce(e.ends_at,'infinity'::timestamptz)>now()) then
    raise exception 'El equipo tiene mantenimientos o reservas pendientes. Finalízalos o cancélalos antes de retirarlo';
  end if;
  update public.equipment_assets set active=false,status='baja',archived_at=clock_timestamp(),archived_by=auth.uid(),archive_reason=btrim(reason) where id=target_equipment_id;
end $$;
create or replace function public.restore_equipment_asset(target_equipment_id uuid,reason text)
returns void language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if not public.is_manager() then raise exception 'Solo el jefe puede restaurar equipos'; end if;
  if length(btrim(coalesce(reason,'')))<3 then raise exception 'Indica el motivo de restauración'; end if;
  update public.equipment_assets set active=true,status='desconocido',archived_at=null,archived_by=null,archive_reason=null where id=target_equipment_id and not active;
  if not found then raise exception 'Equipo retirado no encontrado'; end if;
  insert into public.audit_log(actor_id,action,entity_type,entity_id,metadata) values(auth.uid(),'equipment_restore','equipment_assets',target_equipment_id::text,jsonb_build_object('reason',btrim(reason)));
end $$;
create or replace function public.ensure_active_equipment_schedule()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if new.equipment_id is not null and new.status in ('programado','en_proceso','programada','en_curso') then
    perform pg_advisory_xact_lock(20261122,20);
    if not exists(select 1 from public.equipment_assets where id=new.equipment_id and active) then raise exception 'El equipo fue retirado o no está disponible'; end if;
  end if;
  return new;
end $$;
create trigger ensure_active_equipment_schedule before insert or update of equipment_id,status,scheduled_at,scheduled_end_at on public.maintenances for each row execute function public.ensure_active_equipment_schedule();
create trigger ensure_active_equipment_schedule before insert or update of equipment_id,status,scheduled_at,scheduled_end_at on public.trainings for each row execute function public.ensure_active_equipment_schedule();
create or replace function public.list_archived_equipment()
returns jsonb language plpgsql stable security definer set search_path=public,pg_temp as $$
begin
  if not public.is_manager() then raise exception 'Solo el jefe puede consultar equipos retirados'; end if;
  return(select coalesce(jsonb_agg(jsonb_build_object('id',a.id,'inventory_code',a.inventory_code,'equipment_type',d.equipment_type,'archive_reason',a.archive_reason) order by a.archived_at desc),'[]'::jsonb) from public.equipment_assets a join public.equipment_inventory_detail d on d.id=a.id where not a.active);
end $$;
revoke all on function public.validate_report_incident_option(),public.remember_report_incident_option(),public.ensure_active_equipment_schedule() from public,anon,authenticated;
revoke all on function public.get_equipment_incident_options(uuid),public.equipment_admin_context(uuid),public.save_equipment_asset(uuid,jsonb,text),public.archive_equipment_asset(uuid,text),public.restore_equipment_asset(uuid,text),public.list_archived_equipment() from public,anon;
grant execute on function public.get_equipment_incident_options(uuid),public.equipment_admin_context(uuid),public.save_equipment_asset(uuid,jsonb,text),public.archive_equipment_asset(uuid,text),public.restore_equipment_asset(uuid,text),public.list_archived_equipment() to authenticated;
create or replace function public.edit_report_incident(target_report_id bigint, changes jsonb, expected_edited_at timestamptz)
returns public.reports language plpgsql security definer set search_path = public, pg_temp as $$
declare old_row public.reports; result public.reports;
begin
  if not public.has_active_profile() then raise exception 'Perfil activo requerido'; end if;
  select * into old_row from public.reports where id = target_report_id and reporter_id = auth.uid() for update;
  if old_row.id is null then raise exception 'Solo el autor puede editar su reporte'; end if;
  if clock_timestamp() >= old_row.created_at + interval '10 minutes' then raise exception 'El margen de 10 minutos ha terminado'; end if;
  if old_row.edited_at is distinct from expected_edited_at then raise exception 'El reporte cambió. Recarga la vista previa'; end if;
  if changes is null or jsonb_typeof(changes) <> 'object' then raise exception 'Cambios inválidos'; end if;
  if exists (select 1 from jsonb_object_keys(changes) k where k not in ('event_date','event_type','description','patient_outcome','action_taken','incident_option_id','incident_label')) then
    raise exception 'Solo pueden corregirse los datos del incidente';
  end if;
  if nullif(btrim(changes->>'description'),'') is null or nullif(btrim(changes->>'event_type'),'') is null
     or nullif(changes->>'event_date','') is null then raise exception 'Completa fecha, tipo y descripción'; end if;
  update public.reports set event_date = (changes->>'event_date')::date,
    event_type = btrim(changes->>'event_type'), description = btrim(changes->>'description'),
    patient_outcome = nullif(changes->>'patient_outcome',''), action_taken = nullif(changes->>'action_taken',''),
    incident_option_id = case when changes ? 'incident_option_id' then nullif(changes->>'incident_option_id','')::bigint else old_row.incident_option_id end,
    incident_label = case when changes ? 'incident_label' then nullif(changes->>'incident_label','') else old_row.incident_label end
  where id = target_report_id returning * into result;
  return result;
end $$;
