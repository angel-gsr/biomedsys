create table if not exists public.user_access_requests (
  id bigint generated by default as identity primary key,
  institutional_id text not null check (institutional_id ~ '^(00|01|02)[0-9]{6}$'),
  full_name text not null,
  role public.app_role not null,
  department text,
  status text not null default 'pendiente' check (status in ('pendiente', 'creado', 'cancelado')),
  requested_by uuid not null default auth.uid() references public.profiles(id),
  created_at timestamptz not null default now()
);
