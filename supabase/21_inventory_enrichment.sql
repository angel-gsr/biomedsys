-- Additional workbook columns; original asset identities and operations are preserved.
begin;
set local lock_timeout='10s';
create table public.inventory_enrichment_batches (
  source_sha256 text primary key check(source_sha256 ~ '^[a-f0-9]{64}$'),
  source_file text not null,
  row_count integer not null check(row_count>0),
  rows_payload jsonb not null,
  imported_at timestamptz not null default now()
);
create table public.equipment_inventory_extensions (
  equipment_id uuid primary key references public.equipment_assets(id),
  maintenance_periodicity text,
  suggested_interval_months smallint check(suggested_interval_months>0),
  periodicity_needs_review boolean not null,
  possible_problems text,
  decommission_notes text,
  warranty_notes text,
  regulatory_notes text,
  source_sha256 text not null references public.inventory_enrichment_batches(source_sha256),
  source_row integer not null check(source_row>1),
  updated_at timestamptz not null default now(),
  check(not periodicity_needs_review or suggested_interval_months is null)
);
create table public.inventory_enrichment_versions (
  id bigint generated by default as identity primary key,
  equipment_id uuid not null references public.equipment_assets(id),
  source_sha256 text not null references public.inventory_enrichment_batches(source_sha256),
  row_data jsonb not null,
  created_at timestamptz not null default now(),
  unique(equipment_id,source_sha256)
);
alter table public.inventory_enrichment_batches enable row level security;
alter table public.equipment_inventory_extensions enable row level security;
alter table public.inventory_enrichment_versions enable row level security;
create policy "staff read inventory enrichment batches" on public.inventory_enrichment_batches for select to authenticated using(public.is_technician_or_manager());
create policy "staff read equipment enrichment" on public.equipment_inventory_extensions for select to authenticated using(public.is_technician_or_manager());
create policy "staff read inventory enrichment history" on public.inventory_enrichment_versions for select to authenticated using(public.is_technician_or_manager());
grant select on public.inventory_enrichment_batches,public.equipment_inventory_extensions,public.inventory_enrichment_versions to authenticated;
revoke insert,update,delete on public.inventory_enrichment_batches,public.equipment_inventory_extensions,public.inventory_enrichment_versions from authenticated,anon;
create trigger audit_equipment_inventory_extensions after insert or update on public.equipment_inventory_extensions
for each row execute function public.write_inventory_audit_log();

create or replace function public.import_inventory_enrichment(file_name text,file_sha256 text,source_rows jsonb)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare row jsonb; asset public.equipment_inventory_detail; imported integer:=0; previous jsonb;
begin
  if file_sha256 !~ '^[a-f0-9]{64}$' or nullif(btrim(file_name),'') is null then raise exception 'Fuente inválida'; end if;
  if jsonb_typeof(source_rows)<>'array' or jsonb_array_length(source_rows)=0 then raise exception 'Lote vacío'; end if;
  perform pg_advisory_xact_lock(20261123,21);
  select rows_payload into previous from public.inventory_enrichment_batches where source_sha256=file_sha256;
  if found then
    if previous<>source_rows then raise exception 'El mismo archivo identifica contenidos diferentes'; end if;
    return jsonb_build_object('already_imported',true,'rows',jsonb_array_length(source_rows));
  end if;
  if (select count(distinct x->>'inventory_code') from jsonb_array_elements(source_rows) x)<>jsonb_array_length(source_rows) then raise exception 'Códigos duplicados'; end if;
  -- Validate every identity before storing any source data. Serial duplicates are allowed across different codes.
  for row in select value from jsonb_array_elements(source_rows) loop
    select * into asset from public.equipment_inventory_detail where inventory_code=row->>'inventory_code';
    if asset.id is null then raise exception 'Equipo no encontrado: %',row->>'inventory_code'; end if;
    if lower(btrim(coalesce(asset.equipment_type,'')))<>lower(btrim(coalesce(row#>>'{expected_identity,equipment_type}','')))
       or lower(btrim(coalesce(asset.manufacturer,'')))<>lower(btrim(coalesce(row#>>'{expected_identity,manufacturer}','')))
       or lower(btrim(coalesce(asset.model,'')))<>lower(btrim(coalesce(row#>>'{expected_identity,model}','')))
       or lower(btrim(coalesce(asset.serial_number,'')))<>lower(btrim(coalesce(row#>>'{expected_identity,serial_number}',''))) then
      raise exception 'La identidad no coincide para %; revisar antes de importar',asset.inventory_code;
    end if;
  end loop;
  insert into public.inventory_enrichment_batches(source_sha256,source_file,row_count,rows_payload)
  values(file_sha256,file_name,jsonb_array_length(source_rows),source_rows);
  for row in select value from jsonb_array_elements(source_rows) loop
    select * into asset from public.equipment_inventory_detail where inventory_code=row->>'inventory_code';
    insert into public.equipment_inventory_extensions(equipment_id,maintenance_periodicity,suggested_interval_months,
      periodicity_needs_review,possible_problems,decommission_notes,warranty_notes,regulatory_notes,source_sha256,source_row)
    values(asset.id,row->>'maintenance_periodicity',(row->>'suggested_interval_months')::smallint,
      (row->>'periodicity_needs_review')::boolean,row->>'possible_problems',row->>'decommission_notes',
      row->>'warranty_notes',row->>'regulatory_notes',file_sha256,(row->>'source_row')::integer)
    on conflict(equipment_id) do update set maintenance_periodicity=excluded.maintenance_periodicity,
      suggested_interval_months=excluded.suggested_interval_months,periodicity_needs_review=excluded.periodicity_needs_review,
      possible_problems=excluded.possible_problems,decommission_notes=excluded.decommission_notes,
      warranty_notes=excluded.warranty_notes,regulatory_notes=excluded.regulatory_notes,
      source_sha256=excluded.source_sha256,source_row=excluded.source_row,updated_at=clock_timestamp();
    insert into public.inventory_enrichment_versions(equipment_id,source_sha256,row_data) values(asset.id,file_sha256,row);
    imported:=imported+1;
  end loop;
  return jsonb_build_object('already_imported',false,'rows',imported);
end $$;
-- Import is an owner-side deployment operation, never callable from the browser.
revoke all on function public.import_inventory_enrichment(text,text,jsonb) from public,anon,authenticated;
notify pgrst,'reload schema';
commit;
