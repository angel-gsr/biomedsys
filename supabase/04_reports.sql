create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  report_number text generated always as ('REP-' || lpad(id::text, 6, '0')) stored unique,
  reporter_id uuid not null default auth.uid() references public.profiles(id),
  maintenance_id bigint references public.maintenances(id),
  equipment_identifier text not null,
  event_date date not null,
  event_type text not null,
  service text not null,
  location text,
  manufacturer text,
  model_serial text,
  description text not null,
  patient_outcome text,
  action_taken text,
  priority text not null default 'Ordinaria' check (priority in ('Crítica', 'Alta', 'Ordinaria')),
  status text not null default 'Recibido' check (status in ('Recibido', 'Clasificado', 'Asignado', 'En atención', 'Resuelto', 'Cerrado')),
  created_at timestamptz not null default now()
);
