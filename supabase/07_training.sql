create table if not exists public.trainings (
  id bigint generated by default as identity primary key,
  training_number text generated always as ('CAP-' || lpad(id::text, 6, '0')) stored unique,
  title text not null,
  purpose text not null check (purpose in ('equipo_nuevo', 'personal_nuevo', 'necesidad_detectada', 'protocolo')),
  recurrence text not null check (recurrence in ('semanal', 'mensual', 'semestral', 'anual', 'unica')),
  scheduled_at timestamptz not null,
  location text,
  instructor_id uuid not null references public.profiles(id),
  description text,
  status text not null default 'programada' check (status in ('programada', 'en_curso', 'completada', 'cancelada')),
  created_at timestamptz not null default now()
);

create table if not exists public.training_participants (
  training_id bigint not null references public.trainings(id) on delete cascade,
  participant_id uuid not null references public.profiles(id) on delete cascade,
  attendance_status text not null default 'convocado' check (attendance_status in ('convocado', 'confirmado', 'asistio', 'no_asistio')),
  primary key (training_id, participant_id)
);
