create table if not exists public.maintenance_catalog (
  code text primary key check (code in ('MP', 'IN', 'MC')),
  type public.maintenance_type not null unique,
  label text not null,
  description text not null
);

insert into public.maintenance_catalog (code, type, label, description) values
  ('MP', 'preventivo', 'Preventivo', 'Revisión programada para conservar el desempeño del equipo.'),
  ('IN', 'inspeccion', 'Inspección', 'Verificación visual, funcional y de seguridad.'),
  ('MC', 'correctivo', 'Correctivo', 'Atención de una falla reportada y documentada.')
on conflict (code) do update set
  type = excluded.type,
  label = excluded.label,
  description = excluded.description;

create table if not exists public.maintenances (
  id bigint generated by default as identity primary key,
  maintenance_number text not null unique,
  maintenance_code text not null references public.maintenance_catalog(code),
  equipment_identifier text,
  status text not null default 'programado' check (status in ('programado', 'en_proceso', 'completado', 'cancelado')),
  scheduled_at timestamptz not null,
  assigned_to uuid references public.profiles(id),
  created_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);

create or replace function public.set_maintenance_number()
returns trigger language plpgsql as $$
begin
  if new.maintenance_number is null or new.maintenance_number = '' then
    new.maintenance_number := 'MT-' || extract(year from new.created_at)::text || '-' ||
      new.maintenance_code || '-' || lpad(new.id::text, 4, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists set_maintenance_number_before_insert on public.maintenances;
create trigger set_maintenance_number_before_insert
before insert on public.maintenances
for each row execute function public.set_maintenance_number();

create table if not exists public.maintenance_activities (
  id bigint generated by default as identity primary key,
  maintenance_id bigint not null references public.maintenances(id) on delete cascade,
  activity text not null,
  completed boolean not null default false,
  notes text
);
