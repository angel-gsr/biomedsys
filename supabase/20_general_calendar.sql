-- One general calendar over real maintenance, training and operating-room bookings.
begin;
set local lock_timeout = '10s';

alter table public.maintenances
  add column scheduled_end_at timestamptz,
  add column calendar_location_id bigint references public.equipment_locations(id),
  add constraint maintenance_calendar_interval check (scheduled_end_at is null or scheduled_end_at > scheduled_at);
alter table public.trainings
  add column scheduled_end_at timestamptz,
  add column calendar_location_id bigint references public.equipment_locations(id),
  add constraint training_calendar_interval check (scheduled_end_at is null or scheduled_end_at > scheduled_at);

create table public.calendar_bookings (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('cirugia','uso_equipo')),
  title text not null check (nullif(btrim(title),'') is not null),
  starts_at timestamptz not null,
  ends_at timestamptz not null check (ends_at > starts_at),
  location_id bigint references public.equipment_locations(id),
  equipment_ids uuid[] not null default '{}',
  status text not null default 'programado' check (status in ('programado','cancelado')),
  created_by uuid not null default auth.uid() references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (kind <> 'cirugia' or location_id is not null),
  check (kind <> 'uso_equipo' or cardinality(equipment_ids) > 0)
);
alter table public.calendar_bookings enable row level security;
create policy "biomedical staff read calendar bookings" on public.calendar_bookings for select to authenticated
using (public.is_technician_or_manager());
grant select on public.calendar_bookings to authenticated;
revoke insert,update,delete on public.calendar_bookings from authenticated,anon;
create trigger audit_calendar_bookings after insert or update on public.calendar_bookings
for each row execute function public.write_inventory_audit_log();
create index calendar_bookings_start_idx on public.calendar_bookings(starts_at);

create or replace function public.calendar_resource_events()
returns table(event_key text,kind text,title text,starts_at timestamptz,ends_at timestamptz,
  location_id bigint,equipment_ids uuid[],status text,blocks_resources boolean)
language sql stable security definer set search_path = public, pg_temp as $$
  select 'reserva:'||b.id,b.kind,b.title,b.starts_at,b.ends_at,b.location_id,b.equipment_ids,b.status,b.status='programado'
  from public.calendar_bookings b
  union all
  select 'mantenimiento:'||m.id,'mantenimiento',m.maintenance_number||coalesce(' · '||m.equipment_identifier,''),
    m.scheduled_at,m.scheduled_end_at,m.calendar_location_id,
    case when m.equipment_id is null then '{}'::uuid[] else array[m.equipment_id] end,m.status,m.status in ('programado','en_proceso')
  from public.maintenances m
  union all
  select 'capacitacion:'||t.id,'capacitacion',t.title,t.scheduled_at,t.scheduled_end_at,t.calendar_location_id,
    case when t.equipment_id is null then '{}'::uuid[] else array[t.equipment_id] end,t.status,t.status in ('programada','en_curso')
  from public.trainings t
$$;

create or replace function public.assert_calendar_availability(target_key text,start_time timestamptz,end_time timestamptz,
  target_location bigint,target_equipment uuid[])
returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare collision record;
begin
  -- Serialize schedule mutations across all three source tables.
  perform pg_advisory_xact_lock(20261122,20);
  if start_time is null or (end_time is not null and end_time <= start_time) then raise exception 'El fin debe ser posterior al inicio'; end if;
  select e.* into collision from public.calendar_resource_events() e
  where e.event_key <> target_key and e.blocks_resources
    and e.starts_at < coalesce(end_time,'infinity'::timestamptz)
    and start_time < coalesce(e.ends_at,'infinity'::timestamptz)
    and ((target_location is not null and e.location_id=target_location)
      or e.equipment_ids && coalesce(target_equipment,'{}'::uuid[]))
  order by e.starts_at limit 1;
  if found then raise exception 'Conflicto de horario con % (%). Selecciona otra fecha, sala o equipo. Si falta una hora de fin, complétala primero.',collision.title,collision.event_key; end if;
end $$;

create or replace function public.guard_calendar_schedule()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
declare eq uuid[]; room bigint; start_time timestamptz; end_time timestamptz; key text; enabled boolean;
begin
  if tg_table_name='calendar_bookings' then
    eq:=new.equipment_ids;room:=new.location_id;start_time:=new.starts_at;end_time:=new.ends_at;
    key:='reserva:'||new.id;enabled:=new.status='programado';new.updated_at:=clock_timestamp();
    if exists (select 1 from unnest(eq) requested(equipment_id) where not exists (select 1 from public.equipment_assets a where a.id=requested.equipment_id and a.active)) then raise exception 'Equipo no disponible'; end if;
  elsif tg_table_name='maintenances' then
    eq:=case when new.equipment_id is null then '{}'::uuid[] else array[new.equipment_id] end;
    room:=new.calendar_location_id;start_time:=new.scheduled_at;end_time:=new.scheduled_end_at;
    key:='mantenimiento:'||new.id;enabled:=new.status in ('programado','en_proceso');
    if enabled and new.maintenance_program_id is not null then
      perform pg_advisory_xact_lock(20261122,20);
      if exists(select 1 from public.maintenances m where m.id<>new.id and m.equipment_id=new.equipment_id
        and m.maintenance_program_id=new.maintenance_program_id and m.status in ('programado','en_proceso')) then
        raise exception 'Ya existe una orden preventiva activa para este equipo y rutina';
      end if;
    end if;
  else
    eq:=case when new.equipment_id is null then '{}'::uuid[] else array[new.equipment_id] end;
    room:=new.calendar_location_id;start_time:=new.scheduled_at;end_time:=new.scheduled_end_at;
    key:='capacitacion:'||new.id;enabled:=new.status in ('programada','en_curso');
  end if;
  if enabled then perform public.assert_calendar_availability(key,start_time,end_time,room,eq); end if;
  return new;
end $$;
create trigger guard_calendar_bookings before insert or update on public.calendar_bookings
for each row execute function public.guard_calendar_schedule();
create trigger guard_maintenance_calendar before insert or update of scheduled_at,scheduled_end_at,calendar_location_id,equipment_id,status on public.maintenances
for each row execute function public.guard_calendar_schedule();
create trigger guard_training_calendar before insert or update of scheduled_at,scheduled_end_at,calendar_location_id,equipment_id,status on public.trainings
for each row execute function public.guard_calendar_schedule();

create or replace function public.list_general_calendar(from_time timestamptz,to_time timestamptz)
returns jsonb language plpgsql stable security definer set search_path = public, pg_temp as $$
declare result jsonb;
begin
  if not public.is_technician_or_manager() then raise exception 'Solo personal biomédico activo'; end if;
  if from_time is null or to_time is null or to_time <= from_time or to_time-from_time > interval '400 days' then raise exception 'Rango de calendario inválido'; end if;
  select coalesce(jsonb_agg(to_jsonb(e)||jsonb_build_object('location_name',
    (select h.name||' · '||l.name from public.equipment_locations l join public.hospital_areas h on h.id=l.hospital_area_id where l.id=e.location_id)) order by e.starts_at),'[]'::jsonb)
  into result from public.calendar_resource_events() e
  where e.starts_at < to_time and coalesce(e.ends_at,'infinity'::timestamptz)>from_time
    and e.status not in ('cancelado','cancelada');
  return result;
end $$;

create or replace function public.general_calendar_options()
returns jsonb language plpgsql stable security definer set search_path = public, pg_temp as $$
begin
  if not public.is_technician_or_manager() then raise exception 'Solo personal biomédico activo'; end if;
  return jsonb_build_object(
    'locations',(select coalesce(jsonb_agg(jsonb_build_object('id',l.id,'name',h.name||' · '||l.name) order by h.name,l.name),'[]'::jsonb) from public.equipment_locations l join public.hospital_areas h on h.id=l.hospital_area_id where l.active and h.active),
    'equipment',(select coalesce(jsonb_agg(jsonb_build_object('id',a.id,'name',a.inventory_code||' · '||et.name) order by a.inventory_code),'[]'::jsonb) from public.equipment_assets a join public.equipment_models m on m.id=a.equipment_model_id join public.equipment_types et on et.id=m.equipment_type_id where a.active),
    'programs',(select coalesce(jsonb_agg(jsonb_build_object('equipment_id',ep.equipment_id,'id',p.id,'name',p.name)),'[]'::jsonb) from public.equipment_maintenance_programs ep join public.maintenance_programs p on p.id=ep.maintenance_program_id where p.active),
    'technicians',(select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'name',p.full_name)),'[]'::jsonb) from public.profiles p where p.active and p.role='tecnico')
  );
end $$;

create or replace function public.save_general_calendar_event(target_key text,event_kind text,event_title text,start_time timestamptz,
  end_time timestamptz,target_location bigint,target_equipment uuid[],target_program bigint default null,target_assignee uuid default null)
returns text language plpgsql security definer set search_path = public, pg_temp as $$
declare key text; source_id bigint; eq uuid[]:=coalesce(target_equipment,'{}'::uuid[]); eq_code text; location_label text;
begin
  if not public.is_manager() then raise exception 'Solo el jefe puede programar eventos'; end if;
  if event_kind <> 'mantenimiento' and nullif(btrim(event_title),'') is null then raise exception 'El título es obligatorio'; end if;
  if start_time is null or end_time is null or end_time<=start_time then raise exception 'Registra inicio y fin válidos'; end if;
  if target_location is not null and not exists(select 1 from public.equipment_locations where id=target_location and active) then raise exception 'Sala no disponible'; end if;
  if exists(select 1 from unnest(eq) requested(equipment_id) where not exists(select 1 from public.equipment_assets a where a.id=requested.equipment_id and a.active)) then raise exception 'Equipo no disponible'; end if;
  if cardinality(eq)<>(select count(distinct id) from unnest(eq) id) then raise exception 'Equipo duplicado'; end if;
  if target_assignee is not null and not exists(select 1 from public.profiles where id=target_assignee and role='tecnico' and active) then raise exception 'Técnico no disponible'; end if;
  perform pg_advisory_xact_lock(20261122,20);
  if target_key is null then
    if start_time < now() then raise exception 'Programa un horario futuro'; end if;
    if event_kind in ('cirugia','uso_equipo') then
      insert into public.calendar_bookings(kind,title,starts_at,ends_at,location_id,equipment_ids)
      values(event_kind,btrim(event_title),start_time,end_time,target_location,eq) returning 'reserva:'||id into key;
    elsif event_kind='mantenimiento' then
      if cardinality(eq)<>1 or target_program is null then raise exception 'Selecciona equipo y rutina preventiva'; end if;
      if not exists(select 1 from public.equipment_maintenance_programs where equipment_id=eq[1] and maintenance_program_id=target_program) then raise exception 'Rutina no vinculada al equipo'; end if;
      if exists(select 1 from public.maintenances where equipment_id=eq[1] and maintenance_program_id=target_program and status in ('programado','en_proceso')) then raise exception 'Ya existe una orden preventiva activa para este equipo y rutina'; end if;
      select inventory_code into eq_code from public.equipment_assets where id=eq[1];
      insert into public.maintenances(maintenance_number,maintenance_code,equipment_identifier,equipment_id,maintenance_program_id,scheduled_at,scheduled_end_at,calendar_location_id,assigned_to,created_by,priority)
      values('','MP',eq_code,eq[1],target_program,start_time,end_time,target_location,target_assignee,auth.uid(),'ordinaria') returning 'mantenimiento:'||id into key;
    elsif event_kind='capacitacion' then
      if cardinality(eq)>1 then raise exception 'La capacitación admite un equipo vinculado'; end if;
      select name into location_label from public.equipment_locations where id=target_location;
      insert into public.trainings(title,purpose,recurrence,scheduled_at,scheduled_end_at,calendar_location_id,location,instructor_id,equipment_id,status)
      values(btrim(event_title),'protocolo','unica',start_time,end_time,target_location,location_label,coalesce(target_assignee,auth.uid()),eq[1],'programada') returning 'capacitacion:'||id into key;
    else raise exception 'Tipo de evento inválido'; end if;
  else
    source_id:=split_part(target_key,':',2)::bigint;key:=target_key;
    if target_key like 'reserva:%' and event_kind in ('cirugia','uso_equipo') then
      update public.calendar_bookings set title=btrim(event_title),starts_at=start_time,ends_at=end_time,location_id=target_location,equipment_ids=eq
      where id=source_id and kind=event_kind and status='programado';
    elsif target_key like 'mantenimiento:%' and event_kind='mantenimiento' then
      update public.maintenances set scheduled_at=start_time,scheduled_end_at=end_time,calendar_location_id=target_location
      where id=source_id and status in ('programado','en_proceso');
    elsif target_key like 'capacitacion:%' and event_kind='capacitacion' then
      update public.trainings set scheduled_at=start_time,scheduled_end_at=end_time,calendar_location_id=target_location
      where id=source_id and status in ('programada','en_curso');
    else raise exception 'Evento incompatible'; end if;
    if not found then raise exception 'Evento no disponible para editar'; end if;
  end if;
  return key;
end $$;

create or replace function public.cancel_general_calendar_event(target_key text)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare source_id bigint:=split_part(target_key,':',2)::bigint;
begin
  if not public.is_manager() then raise exception 'Solo el jefe puede cancelar eventos'; end if;
  perform pg_advisory_xact_lock(20261122,20);
  if target_key like 'reserva:%' then update public.calendar_bookings set status='cancelado' where id=source_id and status='programado';
  elsif target_key like 'mantenimiento:%' then update public.maintenances set status='cancelado' where id=source_id and status in ('programado','en_proceso');
  elsif target_key like 'capacitacion:%' then update public.trainings set status='cancelada' where id=source_id and status in ('programada','en_curso');
  else raise exception 'Evento inválido'; end if;
  if not found then raise exception 'Evento no disponible para cancelar'; end if;
end $$;

revoke all on function public.calendar_resource_events(),public.assert_calendar_availability(text,timestamptz,timestamptz,bigint,uuid[]),public.guard_calendar_schedule() from public,anon,authenticated;
revoke all on function public.list_general_calendar(timestamptz,timestamptz),public.general_calendar_options(),
  public.save_general_calendar_event(text,text,text,timestamptz,timestamptz,bigint,uuid[],bigint,uuid),public.cancel_general_calendar_event(text) from public,anon;
grant execute on function public.list_general_calendar(timestamptz,timestamptz),public.general_calendar_options(),
  public.save_general_calendar_event(text,text,text,timestamptz,timestamptz,bigint,uuid[],bigint,uuid),public.cancel_general_calendar_event(text) to authenticated;
notify pgrst,'reload schema';
commit;
